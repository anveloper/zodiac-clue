// ── §1.7 첫 화면 조망 ───────────────────────────────────────
/**
 * 첫 화면에서 **짧은 변**에 최소한 들어와야 하는 칸 수.
 *
 * 근거는 보드 배치다 — 방 3열이 x 1‑5 · 9‑14 · 18‑22에 있다.
 * ⚠️ 「명패는 각 방의 **좌상단**(x칸+10 … +74 px)」이라는 옛 서술은 스테일이다 —
 *    명패는 그 뒤 방 **바깥 위 중앙**으로 나갔고 폭도 최대 144px다(2026-08-29 확인). 폰 세로(390)에서 **명패가 잘리지 않는 방**을
 * 세어 보면 16칸에서는 2개(가운데 열)뿐이고 **17칸에서 6개**가 된다 —
 * 640px 창은 오른쪽 열 명패(≤794px)를 14px 차이로 놓치기 때문이다.
 * 기존값(줌 1.0 = 9.75칸)에서는 방 2개였다.
 *
 * 더 넓히면(19칸) 9개 명패가 다 들어오지만 보드가 화면 높이의 58%로 줄어
 * 이번 과제 ②가 없애려는 «빈 여백»을 되살린다. 17칸이 두 요구의 교차점이다.
 *
 * ~~데스크톱은 이 값으로 계산한 줌이 기본 줌보다 커서 `fitZoom`이 기본값을 돌려준다 —
 * 즉 **데스크톱 줌은 이 상수의 영향을 받지 않는다**(1440×900 → 1.32 → clamp 1.0).~~
 *
 * 🔴 **위 두 줄은 `CELL_PX = 40` 시절의 값이다**(2026-08-29 실측 정정).
 *    지금은 1440×900의 짧은 변이 900이므로 `900 / (17 × 80) = **0.662**` — 기본 줌 1.0보다
 *    작아 clamp되지 않는다. 즉 **데스크톱 줌을 정하는 것이 바로 이 상수**이고,
 *    데스크톱에는 짧은 변에 정확히 17칸이 들어온다. 「영향을 받지 않는다」는 정반대다.
 *
 * 🔴 **바뀐 것은 폰 쪽이다.** `fitZoom`은 `MIN_ZOOM`으로도 clamp하는데 폰에서는 그쪽이
 *    먼저 걸린다: 이 상수가 지배하려면 `short ≥ MIN_ZOOM × 17 × CELL_PX = 0.4 × 17 × 80
 *    = **544px**`이어야 하는데 폰 세로(390)는 그 아래라 줌이 **0.4로 고정**되고
 *    보이는 칸은 17이 아니라 **12.2칸**이다.
 *    ⚠️ 이것은 **원저자의 잘못이 아니다.** 도입 시점(`a5a9e31`)에는 `CELL_PX = 40`·
 *    `MIN_ZOOM = 0.3`이라 폰 줌이 `390/(17×40) = 0.574`로 상수가 **실제로 지배했다**.
 *    무효가 된 것은 `eff7c0f`(셀 40→80 · `MIN_ZOOM` 0.3→0.4)가 **이 상수를 조용히
 *    무효화하고 문서를 안 고쳤기** 때문이다. 「한 번도 실현된 적 없다」가 아니라
 *    **「셀을 두 배로 올리며 무효화했다」**가 사실이다.
 *
 * 값을 지금 바꾸지 않는 이유: 이 상수를 내리면 폰은 그대로고 **데스크톱이 줌인**된다
 * (폰은 `MIN_ZOOM`이 지배하므로). 폰을 넓히려면 `MIN_ZOOM`을 내려야 한다.
 *
 * 🔴 그 근거를 32회차에 갈았다. ~~「이름표가 같이 작아져서」~~ 는 이제 **틀린 근거**다 —
 *    이름표도 역스케일이 붙었고 상한이 `1/MIN_ZOOM`이라 `MIN_ZOOM`을 내리면
 *    **화면 크기는 13px 그대로**다. 진짜 제약은 **월드 폭**이다(최장 이름 실측 89px):
 *      `MIN_ZOOM 0.4 → 223px(2.8칸)` · `0.287 → 310px(3.9칸)` · `0.203(전체 보드) → 438px(5.5칸)`.
 *    한 칸이 80px이므로 줌아웃할수록 이름표가 **판을 뒤덮는다.**
 *    즉 지금 구조(월드에 두고 역스케일)에서는 줌아웃과 라벨이 양립하지 않는다.
 *    ⚠️ 다만 **구조를 바꾸는 길은 있다** — 말풍선(`placeBubble`)처럼 **화면 공간**으로
 *    옮기면 라벨 크기와 월드 점유가 분리된다. 그 밖에 임계 줌 아래에서 이름표를 끄는
 *    LOD, 현재 턴·내 토큰만 켜는 declutter도 있다(플랜 52 큐).
 */
export const INIT_MIN_CELLS = 17;

/**
 * 초기 줌. `short` = 뷰포트 짧은 변(px).
 * 결과는 `[minZoom, baseZoom]` 안이며, 넓은 화면에서는 정확히 `baseZoom`이다.
 */
export const fitZoom = (
  short: number,
  baseZoom: number,
  minZoom: number,
): number =>
  Math.min(
    baseZoom,
    Math.max(minZoom, short / (INIT_MIN_CELLS * CELL_PX)),
  );

